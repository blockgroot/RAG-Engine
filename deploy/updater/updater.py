"""The self-hosted updater: moves this install to a newer Handbook version.

It is the only container with the Docker socket, so it does one thing. Given
a version, it checks that version against our public release list, then runs
the same steps as upgrade.sh: back up the database, set HANDBOOK_VERSION in
.env, pull and restart web, api and worker, and wait until api is healthy. If
api does not come up, it puts the old version back.

The API asks for an update with a shared secret (UPDATER_TOKEN, generated by
install.sh). Nothing it is sent is trusted: the version must be in the feed,
newer than the one running, and not one that needs steps by hand. It never
runs an image other than the ones docker-compose.yml names.

Only web, api and worker are recreated. caddy and db change only with a new
install package, which is a release that needs steps by hand; and recreating
caddy from inside this container would mount the Caddyfile from a path that
exists only in here.

Standard library only, so the image is the Docker CLI plus Python.
"""

from __future__ import annotations

import hmac
import json
import os
import re
import subprocess
import threading
import time
import urllib.request
from datetime import datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

HANDBOOK_DIR = os.environ.get("HANDBOOK_DIR", "/handbook")
ENV_FILE = os.path.join(HANDBOOK_DIR, ".env")
TOKEN = os.environ.get("UPDATER_TOKEN", "")
FEED_URL = os.environ.get("UPDATE_FEED_URL") or (
    "https://raw.githubusercontent.com/blockgroot/handbook-releases/main/releases.json"
)
SERVICES = ["web", "api", "worker"]
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
HEALTH_TRIES = 60  # x 5 seconds
HEALTH_WAIT = 5

_lock = threading.Lock()
_state = {"state": "idle", "version": None, "step": None, "error": None}


def _set(**changes) -> None:
    with _lock:
        _state.update(changes)


def _key(version: str) -> tuple[int, ...]:
    return tuple(int(p) for p in version.split("."))


def read_env(key: str) -> str:
    with open(ENV_FILE) as f:
        for line in f:
            if line.startswith(f"{key}="):
                return line.split("=", 1)[1].strip()
    return ""


def write_env(key: str, value: str) -> None:
    """Replace KEY's line, keeping the file (and its owner-only permissions)."""
    with open(ENV_FILE) as f:
        lines = f.readlines()
    found = False
    for i, line in enumerate(lines):
        if line.startswith(f"{key}="):
            lines[i] = f"{key}={value}\n"
            found = True
    if not found:
        lines.append(f"{key}={value}\n")
    with open(ENV_FILE, "w") as f:
        f.writelines(lines)


def compose(*args: str, stdout=None) -> subprocess.CompletedProcess:
    # Without HANDBOOK_* in this process's environment, compose reads them
    # from .env, which is what this script changes.
    env = {k: v for k, v in os.environ.items() if not k.startswith("HANDBOOK_")}
    return subprocess.run(
        ["docker", "compose", "--project-directory", HANDBOOK_DIR, *args],
        env=env,
        stdout=stdout if stdout is not None else subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )


def check_version(version: str, current: str) -> str | None:
    """Why ``version`` may not be installed, or None when it may."""
    if not VERSION_RE.match(version):
        return "Not a version number."
    if not VERSION_RE.match(current):
        return "The running version is not known."
    if _key(version) <= _key(current):
        return f"{version} is not newer than {current}."
    with urllib.request.urlopen(FEED_URL, timeout=10) as response:
        feed = json.load(response)
    releases = {r.get("version"): r for r in feed.get("releases", []) if isinstance(r, dict)}
    if version not in releases:
        return f"{version} is not a Handbook release."
    for v, release in releases.items():
        if (
            isinstance(v, str)
            and VERSION_RE.match(v)
            and _key(current) < _key(v) <= _key(version)
            and release.get("manual_steps") is True
        ):
            return f"{v} needs steps on the server; follow its release notes and run upgrade.sh."
    return None


def backup() -> None:
    if read_env("DATABASE_URL"):
        return  # an outside database is backed up by its provider
    os.makedirs(os.path.join(HANDBOOK_DIR, "backups"), exist_ok=True)
    path = os.path.join(
        HANDBOOK_DIR, "backups", f"handbook-{datetime.now():%Y%m%d-%H%M%S}.dump"
    )
    old_umask = os.umask(0o077)
    try:
        with open(path, "wb") as out:
            compose("exec", "-T", "db", "pg_dump", "-U", "handbook", "-Fc", "handbook", stdout=out)
    finally:
        os.umask(old_umask)
    if os.path.getsize(path) == 0:
        raise RuntimeError("The backup came out empty.")


def wait_healthy() -> bool:
    for _ in range(HEALTH_TRIES):
        container = compose("ps", "-q", "api").stdout.decode().strip()
        if container:
            health = subprocess.run(
                ["docker", "inspect", "-f", "{{.State.Health.Status}}", container],
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            ).stdout.decode().strip()
            if health == "healthy":
                return True
        time.sleep(HEALTH_WAIT)
    return False


def registry_login() -> None:
    """Private images need the pull token in here too: a ``docker login`` on
    the server stores it for that user, not for this container."""
    user, token = read_env("REGISTRY_USERNAME"), read_env("REGISTRY_TOKEN")
    if not (user and token):
        return
    registry = (read_env("HANDBOOK_REGISTRY") or "ghcr.io/blockgroot").split("/")[0]
    subprocess.run(
        ["docker", "login", registry, "-u", user, "--password-stdin"],
        input=token.encode(),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )


def switch_to(version: str) -> bool:
    write_env("HANDBOOK_VERSION", version)
    _set(step="pull")
    registry_login()
    compose("pull", *SERVICES)
    _set(step="restart")
    compose("up", "-d", "--no-deps", *SERVICES)
    _set(step="health")
    return wait_healthy()


def run_update(version: str, previous: str) -> None:
    try:
        _set(step="backup")
        backup()
        if switch_to(version):
            _set(state="done", step=None)
            return
        error = f"Handbook {version} did not start."
    except subprocess.CalledProcessError as exc:
        error = (exc.stderr or b"").decode(errors="replace").strip()[-500:] or str(exc)
    except Exception as exc:  # noqa: BLE001 - reported to the admin, then rolled back
        error = str(exc)
    if read_env("HANDBOOK_VERSION") != previous:
        _set(step="rollback")
        try:
            switch_to(previous)
            _set(state="rolled_back", step=None, error=error)
            return
        except Exception as exc:  # noqa: BLE001
            error = f"{error} Going back also failed: {exc}"
    _set(state="failed", step=None, error=error)


class Handler(BaseHTTPRequestHandler):
    def _reply(self, code: int, body: dict) -> None:
        data = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _authorized(self) -> bool:
        sent = self.headers.get("Authorization", "")
        return bool(TOKEN) and hmac.compare_digest(sent, f"Bearer {TOKEN}")

    def do_GET(self) -> None:
        if self.path == "/health":
            return self._reply(200, {"ok": True})
        if not self._authorized():
            return self._reply(401, {"error": "Not allowed."})
        if self.path == "/status":
            with _lock:
                return self._reply(200, dict(_state))
        self._reply(404, {"error": "Not found."})

    def do_POST(self) -> None:
        if not self._authorized():
            return self._reply(401, {"error": "Not allowed."})
        if self.path != "/update":
            return self._reply(404, {"error": "Not found."})
        try:
            length = min(int(self.headers.get("Content-Length") or 0), 1024)
            version = str(json.loads(self.rfile.read(length) or b"{}").get("version", ""))
        except (ValueError, AttributeError):
            return self._reply(400, {"error": "Send a version."})
        with _lock:
            if _state["state"] == "running":
                return self._reply(409, {"error": "An update is already running."})
        current = read_env("HANDBOOK_VERSION")
        try:
            problem = check_version(version, current)
        except Exception:  # noqa: BLE001
            problem = "Could not read the list of Handbook releases."
        if problem:
            return self._reply(409, {"error": problem})
        _set(state="running", version=version, step="backup", error=None)
        threading.Thread(target=run_update, args=(version, current), daemon=True).start()
        with _lock:
            self._reply(202, dict(_state))

    def log_message(self, fmt: str, *args) -> None:  # requests, not secrets
        print(f"updater: {self.command} {self.path}", flush=True)


if __name__ == "__main__":
    if not TOKEN:
        print("updater: UPDATER_TOKEN is not set; every request will be refused.", flush=True)
    ThreadingHTTPServer(("0.0.0.0", 8080), Handler).serve_forever()
